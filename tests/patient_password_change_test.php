<?php
require __DIR__ . '/../includes/patient_password_change.php';
$pdo = new PDO('sqlite::memory:');
$pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
$pdo->exec('CREATE TABLE users (id INTEGER PRIMARY KEY, password TEXT)');
$original = password_hash('OldPassword123', PASSWORD_DEFAULT);
$pdo->prepare('INSERT INTO users VALUES (1, ?)')->execute([$original]);
$user = ['id' => 1, 'password' => $original, 'email' => 'patient@example.com', 'phone' => '09123456789'];
$session = [];
$code = $destination = '';
$sender = function ($to, $name, $otp, $purpose) use (&$code, &$destination) { $code = $otp; $destination = $to; return true; };
$check = function ($ok, $label) { if (!$ok) throw new RuntimeException($label); echo "PASS: $label\n"; };
$run = function ($input) use ($pdo, &$user, &$session, $sender) { return patientPasswordChange($pdo, $user, $session, $input, $sender); };
$prepare = ['action' => 'change_password', 'current_password' => 'OldPassword123', 'new_password' => 'NewPassword123', 'confirm_password' => 'NewPassword123'];
$read = function () use ($pdo) { return $pdo->query('SELECT password FROM users WHERE id=1')->fetchColumn(); };
$check(count(patientPasswordContacts($user)) === 2, 'Both contacts available');
$check(array_keys(patientPasswordContacts(array_replace($user, ['phone' => '']))) === ['email'], 'Email-only account supported');
$check($run(array_replace($prepare, ['current_password' => 'wrong']))['type'] === 'error', 'Wrong current password rejected');
$check($run(array_replace($prepare, ['confirm_password' => 'different']))['type'] === 'error', 'Password mismatch rejected');
$check($run($prepare)['type'] === 'success' && empty($session['patient_password_change']['otp']) && $read() === $original, 'Save prepares change without sending OTP or updating password');
$check($run(['action' => 'send_password_otp', 'password_channel' => 'other'])['type'] === 'error', 'Unknown contact rejected');
$check($run(['action' => 'send_password_otp', 'password_channel' => 'phone'])['type'] === 'success' && $destination === $user['phone'], 'Selected SMS destination used');
$check($run(['action' => 'send_password_otp', 'password_channel' => 'email'])['type'] === 'error', 'Resend cooldown enforced');
$wrong = $code === '000000' ? '000001' : '000000';
$check($run(['action' => 'verify_password_otp', 'password_otp' => $wrong])['type'] === 'error' && $read() === $original, 'Wrong OTP leaves password unchanged');
$check($run(['action' => 'verify_password_otp', 'password_otp' => $code])['type'] === 'success' && password_verify('NewPassword123', $read()) && empty($session['patient_password_change']), 'Verified OTP saves password and clears pending change');
$user['password'] = $read();
$prepare['current_password'] = 'NewPassword123';
$run($prepare);
$run(['action' => 'send_password_otp', 'password_channel' => 'email']);
$check($destination === $user['email'], 'Selected email destination used');
$session['patient_password_change']['otp_expires'] = time() - 1;
$check($run(['action' => 'verify_password_otp', 'password_otp' => $code])['type'] === 'error' && empty($session['patient_password_change']['otp']), 'Expired OTP cannot save');
$run($prepare);
$run(['action' => 'send_password_otp', 'password_channel' => 'email']);
$wrong = $code === '000000' ? '000001' : '000000';
for ($i = 0; $i < 5; $i++) $run(['action' => 'verify_password_otp', 'password_otp' => $wrong]);
$check(empty($session['patient_password_change']), 'Five wrong attempts cancel pending change');
$run($prepare);
$session['patient_password_change']['user_id'] = 2;
$check($run(['action' => 'send_password_otp', 'password_channel' => 'email'])['type'] === 'error', 'Pending change bound to account');
$run($prepare);
$session['patient_password_change']['original'] = 'stale';
$check($run(['action' => 'send_password_otp', 'password_channel' => 'email'])['type'] === 'error', 'Stale password change rejected');
$run($prepare);
$result = patientPasswordChange($pdo, $user, $session, ['action' => 'send_password_otp', 'password_channel' => 'email'], function () { return false; });
$check($result['type'] === 'error' && empty($session['patient_password_change']['otp']), 'Failed delivery does not enable verification');
$run(['action' => 'cancel_password_otp']);
$check(empty($session['patient_password_change']), 'Cancel clears pending password');
$user['email'] = '';
$check(array_keys(patientPasswordContacts($user)) === ['phone'], 'Phone-only account supported');
$user['phone'] = '';
$check($run($prepare)['type'] === 'error', 'No-contact account cannot request password change');
